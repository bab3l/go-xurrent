//go:build integration

// TestFixture_ParentIDsForCapture discovers IDs from GET lists (and optional POST calendar) and writes
// test/integration/_live_shapes/parent_fixture.env for use with live_capture_pipeline.py --load-parent-fixture.
//
//   set XURRENT_BUILD_PARENT_FIXTURE=1
//   go test -tags=integration ./test/integration/ -run TestFixture_ParentIDsForCapture -v -count=1
//
// Or: python utils/live_capture_pipeline.py --parent-fixture --go-test-run TestFixture_ParentIDsForCapture

package integration_test

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"

	openapiclient "github.com/xurrent/go-xurrent"
)

func fixtureDiscoveryClient(t *testing.T) *openapiclient.APIClient {
	t.Helper()
	if os.Getenv("XURRENT_TOKEN") == "" || os.Getenv("XURRENT_ACCOUNT") == "" {
		t.Skip("set XURRENT_TOKEN and XURRENT_ACCOUNT")
	}
	cfg := newIntegrationConfig(t, true)
	return openapiclient.NewAPIClient(cfg)
}

// TestFixture_ParentIDsForCapture writes parent_fixture.env with discovered IDs (non-destructive GETs + optional POST calendar).
func TestFixture_ParentIDsForCapture(t *testing.T) {
	if os.Getenv("XURRENT_BUILD_PARENT_FIXTURE") != "1" {
		t.Skip("set XURRENT_BUILD_PARENT_FIXTURE=1 (live_capture_pipeline.py --parent-fixture) to write parent_fixture.env")
	}
	client := fixtureDiscoveryClient(t)
	ctx := context.Background()
	acc := os.Getenv("XURRENT_ACCOUNT")

	out := make(map[string]string)

	if rid, ok := firstOpenRequestID(t, ctx, client); ok {
		out["XURRENT_TEST_OPEN_REQUEST_ID"] = fmt.Sprintf("%d", rid)
		t.Logf("open request id=%d", rid)
	}

	// Problems list → first id (GET returns *http.Response in client — use same pattern as write_shape)
	if pid, ok := firstIDFromJSONArrayResponse(client.ProblemsAPI.GetProblems(ctx).PerPage(1).Fields("id").Execute()); ok {
		out["XURRENT_TEST_PROBLEM_ID"] = fmt.Sprintf("%d", pid)
		t.Logf("problem id from list=%d", pid)
	}

	// Workflow id from list when env not set
	if os.Getenv("XURRENT_TEST_WORKFLOW_ID") == "" {
		if m, resp, err := client.WorkflowsAPI.GetWorkflows(ctx).PerPage(1).Fields("id").Execute(); err == nil && resp != nil && resp.StatusCode == 200 {
			if wid, ok := firstIDFromDecodedList(m); ok {
				out["XURRENT_TEST_WORKFLOW_ID"] = fmt.Sprintf("%d", wid)
				t.Logf("workflow id from list=%d", wid)
			}
		}
	}

	// Calendar POST when mutations enabled (live capture pipeline sets ALLOW_MUTATIONS)
	if os.Getenv("XURRENT_ALLOW_MUTATIONS") == "1" {
		sfx := randomSuffix()
		name := fmt.Sprintf("fixture-cal-%s", sfx)
		created, resp, err := client.CalendarsAPI.PostCalendars(ctx).Body(map[string]interface{}{
			"name": name,
		}).Execute()
		if err == nil && resp != nil && resp.StatusCode == 201 {
			requireResourceOwnedByEnvAccountAny(t, acc, created)
			if cid, ok := mapIDInt32Any(created); ok {
				out["XURRENT_TEST_FIXTURE_CALENDAR_ID"] = fmt.Sprintf("%d", cid)
				t.Logf("created calendar id=%d", cid)
			}
		} else {
			t.Logf("PostCalendars for fixture: %v HTTP %v", err, resp)
		}
	}

	// Service: try minimal POST when mutations on (may 422 — still useful to log)
	if os.Getenv("XURRENT_ALLOW_MUTATIONS") == "1" {
		orgID, ok := firstOrganizationID(t, ctx, client)
		if ok {
			sfx := randomSuffix()
			svcCreated, resp, err := client.ServicesAPI.PostServices(ctx).Body(map[string]interface{}{
				"name":     fmt.Sprintf("fixture-svc-%s", sfx),
				"provider": map[string]interface{}{"id": orgID},
			}).Execute()
			if err == nil && resp != nil && resp.StatusCode == 201 {
				requireResourceOwnedByEnvAccountAny(t, acc, svcCreated)
				if sid, ok2 := mapIDInt32Any(svcCreated); ok2 {
					out["XURRENT_TEST_SERVICE_ID"] = fmt.Sprintf("%d", sid)
					t.Logf("created service id=%d", sid)
				}
			} else {
				t.Logf("PostServices fixture skipped: %v", err)
			}
		}
	}

	path := parentFixtureEnvPath(t)
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		t.Fatalf("mkdir: %v", err)
	}
	var b strings.Builder
	b.WriteString("# Generated by TestFixture_ParentIDsForCapture — do not commit secrets.\n")
	for k, v := range out {
		if v == "" {
			continue
		}
		b.WriteString(k)
		b.WriteString("=")
		b.WriteString(v)
		b.WriteString("\n")
	}
	if err := os.WriteFile(path, []byte(b.String()), 0600); err != nil {
		t.Fatalf("write fixture env: %v", err)
	}
	t.Logf("wrote %s (%d keys)", path, len(out))
}
